// Builds the deployable site into dist/.
//
//  - Copies web/ into dist/.
//  - Writes dist/config.js from .env (or real environment variables):
//      SUPABASE_URL, SUPABASE_ANON_KEY
//  - If a brand pack exists (./brand/brand.json, or BRAND_DIR), copies it to
//    dist/brand/ and embeds it, so the app picks up its logo and themes.
//
// .env and brand/ are git-ignored: your keys and your company's branding
// stay on your machine and in your deployment, never in the public repo.
import { readFileSync, writeFileSync, existsSync, rmSync, cpSync, mkdirSync } from 'node:fs';
import { join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = fileURLToPath(new URL('..', import.meta.url));

export function loadEnv() {
  const out = {};
  const file = join(root, '.env');
  if (existsSync(file)) {
    for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
      const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/);
      if (!m) continue;
      let v = m[2];
      if (/^(['"]).*\1$/.test(v)) v = v.slice(1, -1);
      out[m[1]] = v;
    }
  }
  return { ...out, ...process.env };
}

export function build() {
  const env = loadEnv();
  const dist = join(root, 'dist');
  rmSync(dist, { recursive: true, force: true });
  cpSync(join(root, 'web'), dist, { recursive: true });

  const config = { supabaseUrl: env.SUPABASE_URL || '', supabaseAnonKey: env.SUPABASE_ANON_KEY || '' };

  let brand = null;
  const brandDir = resolve(root, env.BRAND_DIR || 'brand');
  const brandFile = join(brandDir, 'brand.json');
  if (existsSync(brandFile)) {
    brand = JSON.parse(readFileSync(brandFile, 'utf8'));
    mkdirSync(join(dist, 'brand'), { recursive: true });
    cpSync(brandDir, join(dist, 'brand'), {
      recursive: true,
      filter: (src) => !src.endsWith('brand.json')
    });
  }

  writeFileSync(join(dist, 'config.js'),
    '// Generated by scripts/build.mjs. Do not edit; change .env or brand/ instead.\n' +
    'window.POKER_CONFIG = ' + JSON.stringify(config) + ';\n' +
    'window.POKER_BRAND = ' + JSON.stringify(brand) + ';\n');

  console.log('Built dist/');
  console.log('  Supabase: ' + (config.supabaseUrl ? config.supabaseUrl : 'NOT SET (add SUPABASE_URL and SUPABASE_ANON_KEY to .env)'));
  console.log('  Brand:    ' + (brand ? (brand.orgName || 'custom') + ' (' + Object.keys(brand.themes || {}).length + ' themes)' : 'none, using built-in themes'));
  return { env, dist };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === resolve(process.argv[1])) build();
